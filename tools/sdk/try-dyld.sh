#!/bin/sh
# SPDX-License-Identifier: BSD-2-Clause (our script; the sources it compiles are Apple open source, APSL-2.0, fetched by fetch-sources.sh)
# usage: run on the FreeBSD VM after fetch-sources.sh, build-migcom.sh, gen-headers.sh, assemble-sdk.sh; also needs llvm-project (libcxx/include, libcxxabi/include, libcxx/vendor) in /root/oss/llvm-libcxx
# syntax-only pass over the dyld sources against the assembled header tree; prints pass/fail and the most common errors
W=/root/oss; I=$W/sdk/usr/include; L=$W/llvm-libcxx/libcxx; C=$W/libcxx-cfg
mkdir -p $I/System/sys $C
cp $W/xnu/bsd/sys/reason.h $I/System/sys/ 2>/dev/null
cp $W/Libc/include/FreeBSD/nl_types.h $I/ 2>/dev/null
cat > $C/__config_site <<'S'
#ifndef _LIBCPP___CONFIG_SITE
#define _LIBCPP___CONFIG_SITE
#define _LIBCPP_ABI_VERSION 1
#define _LIBCPP_ABI_NAMESPACE __1
#define _LIBCPP_ABI_FORCE_ITANIUM 0
#define _LIBCPP_ABI_FORCE_MICROSOFT 0
#define _LIBCPP_HAS_THREADS 1
#define _LIBCPP_HAS_MONOTONIC_CLOCK 1
#define _LIBCPP_HAS_TERMINAL 1
#define _LIBCPP_HAS_MUSL_LIBC 0
#define _LIBCPP_HAS_THREAD_API_PTHREAD 1
#define _LIBCPP_HAS_THREAD_API_EXTERNAL 0
#define _LIBCPP_HAS_THREAD_API_WIN32 0
#define _LIBCPP_HAS_THREAD_API_C11 0
#define _LIBCPP_HAS_VENDOR_AVAILABILITY_ANNOTATIONS 0
#define _LIBCPP_HAS_FILESYSTEM 1
#define _LIBCPP_HAS_RANDOM_DEVICE 1
#define _LIBCPP_HAS_LOCALIZATION 1
#define _LIBCPP_HAS_UNICODE 1
#define _LIBCPP_HAS_WIDE_CHARACTERS 1
#define _LIBCPP_HAS_TIME_ZONE_DATABASE 0
#define _LIBCPP_INSTRUMENTED_WITH_ASAN 0
#define _LIBCPP_PSTL_BACKEND_SERIAL
#define _LIBCPP_HARDENING_MODE_DEFAULT _LIBCPP_HARDENING_MODE_NONE
#endif
S
cp $L/vendor/llvm/default_assertion_handler.in $C/__assertion_handler
# the FreeBSD flavour of Libc's xlocale_private.h is C only: add the casts C++ needs
sed -i "" -e "s/struct xlocale_refcounted \*obj = val;/struct xlocale_refcounted *obj = (struct xlocale_refcounted *)val;/" $I/xlocale_private.h 2>/dev/null
cat > $C/dyld_prelude.h <<'P'
/* generated by trydyld.sh: what the assembled header tree lacks (availability macros are empty; fat_arch_64 from the Mach-O format) */
#ifndef DYLD_PRELUDE_H
#define DYLD_PRELUDE_H
#define __OSX_DEPRECATED(...)
#define __OSX_AVAILABLE(...)
#define __OSX_UNAVAILABLE
#define __OSX_AVAILABLE_STARTING(...)
#define __OSX_AVAILABLE_BUT_DEPRECATED(...)
#define __OSX_AVAILABLE_BUT_DEPRECATED_MSG(...)
#define __API_AVAILABLE(...)
#define __API_UNAVAILABLE(...)
#define __API_DEPRECATED(...)
#define __API_DEPRECATED_WITH_REPLACEMENT(...)
#ifndef FAT_MAGIC_64
#define FAT_MAGIC_64 0xcafebabf
#define FAT_CIGAM_64 0xbfbafeca
#ifdef __cplusplus
extern "C" {
#endif
#include <stdint.h>
struct fat_arch_64 { int32_t cputype; int32_t cpusubtype; uint64_t offset; uint64_t size; uint32_t align; uint32_t reserved; };
#ifdef __cplusplus
}
#endif
#endif
#endif
P
RES=$(ls -d /usr/local/llvm21/lib/clang/*/include | tail -1); CXX=/usr/local/llvm21/bin/clang++
cd $W/dyld
FL="--target=x86_64-apple-macosx14.0 -std=c++20 -fsyntax-only -nostdinc -nostdinc++ -isystem $C -isystem $L/include -isystem $W/llvm-libcxx/libcxxabi/include -isystem $RES -isystem $I -include $C/dyld_prelude.h -I$W/dyld -Idyld/lsl -I$W/libplatform/private -I$W/xnu/libsyscall/wrappers/libproc -Idyld -Icommon -Iinclude -Imach_o -Imach_o_writer -DBUILDING_DYLD=1 -DSUPPORT_VM_LAYOUT=1 -w -ferror-limit=0"
ok=0; bad=0; : > /tmp/dyld-errs.txt; : > /tmp/dyld-fail.txt
for f in dyld/*.cpp common/*.cpp mach_o/*.cpp; do
  if $CXX $FL $f 2>/tmp/e.txt; then ok=$((ok+1)); else bad=$((bad+1)); echo $f >> /tmp/dyld-fail.txt; grep -E "error" /tmp/e.txt | sed -E 's/^[^ ]+ //' >> /tmp/dyld-errs.txt; fi
done
echo "pass: $ok  fail: $bad"; sort /tmp/dyld-errs.txt | uniq -c | sort -rn | head -14
