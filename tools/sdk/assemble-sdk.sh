#!/bin/sh
# assembles a header tree of a Darwin SDK from the open sources that fetch-sources.sh brought (nothing of an Xcode SDK is used) and tries it with a small C program:
#   sh tools/sdk/assemble-sdk.sh [WORK]      -> WORK/sdk/usr/include       (run fetch-sources.sh, build-migcom.sh and gen-headers.sh first)
W="${1:-/root/oss}"; I="$W/sdk/usr/include"; X="$W/xnu"; H="$(cd "$(dirname "$0")" && pwd)"
rm -rf "$W/sdk"; mkdir -p "$I"/sys "$I"/mach "$I"/machine "$I"/i386 "$I"/libkern "$I"/os "$I"/pthread "$I"/dispatch "$I"/uuid "$I"/malloc
cp -R "$W"/CarbonHeaders/*.h "$I"/ 2>/dev/null
cp -R "$X"/EXTERNAL_HEADERS/* "$I"/ 2>/dev/null; rm -f "$I"/Makefile "$I"/Info.plist
cp -R "$W"/Libc/include/* "$I"/ 2>/dev/null
cp -R "$X"/bsd/sys/* "$I"/sys/ 2>/dev/null; cp -R "$X"/bsd/machine/* "$I"/machine/ 2>/dev/null; cp -R "$X"/bsd/i386/* "$I"/i386/ 2>/dev/null
for d in net netinet netinet6 arpa bsm; do [ -d "$X/bsd/$d" ] && { mkdir -p "$I/$d"; cp "$X"/bsd/$d/*.h "$I/$d/" 2>/dev/null; }; done
cp "$X"/bsd/uuid/*.h "$I"/uuid/ 2>/dev/null
cp "$X"/libkern/libkern/*.h "$I"/libkern/ 2>/dev/null; cp -R "$X"/libkern/libkern/* "$I"/libkern/ 2>/dev/null
cp "$X"/osfmk/mach/*.h "$I"/mach/ 2>/dev/null; cp -R "$X"/osfmk/mach/machine "$X"/osfmk/mach/i386 "$I"/mach/ 2>/dev/null
cp -R "$W"/libplatform/include/* "$I"/ 2>/dev/null
cp "$W"/libpthread/include/pthread/*.h "$I"/pthread/; cp "$W"/libpthread/include/pthread/pthread.h "$W"/libpthread/include/pthread/sched.h "$W"/libpthread/include/pthread/spawn.h "$W"/libpthread/include/pthread/qos.h "$I"/ 2>/dev/null; cp -R "$W"/libpthread/include/sys/* "$I"/sys/ 2>/dev/null
cp "$W"/libdispatch/dispatch/*.h "$I"/dispatch/; cp "$W"/libdispatch/os/*.h "$I"/os/ 2>/dev/null
cp "$W"/inc/sys/*.h "$I"/sys/ 2>/dev/null; cp "$W"/libmalloc/include/malloc/*.h "$I"/malloc/ 2>/dev/null
# the headers that MIG makes from the interface definitions of xnu (the user side: mach/mach_vm.h, mach/mach_host.h ...)
MIG="$W/build/mig/migcom"; n=0; f=0
for defs in mach_vm mach_host host_priv host_security task thread_act vm_map mach_port clock clock_priv clock_reply processor processor_set semaphore lock_set exc mach_exc mach_voucher memory_entry notify mach_notify task_access mach_eventlink; do
	[ -f "$X/osfmk/mach/$defs.defs" ] || continue
	if cc -E -x c -undef -D__MIGCOM__ -DKERNEL_USER=1 -DMACH_KERNEL_PRIVATE=0 -nostdinc -I"$I" -I"$X/osfmk" "$X/osfmk/mach/$defs.defs" 2>/dev/null | "$MIG" -header "$I/mach/$defs.h" -user /dev/null -server /dev/null -sheader "$I/mach/${defs}_server.h" >/dev/null 2>&1 && [ -s "$I/mach/$defs.h" ]; then n=$((n+1)); else f=$((f+1)); echo "mig failed: $defs"; fi
done
echo "MIG headers made: $n, failed: $f"
echo "headers in the tree: $(find "$I" -name '*.h' | wc -l)"
# the availability annotations (__API_AVAILABLE(macos(14.0), ..., visionos(1.0), driverkit(23.0)) ...) are attributes that do not change the code: the Availability.h of xnu takes at most four platforms and the
# newer headers pass seven, so here they are all empty (the real header is generated by Apple's availability scripts, which are not open)
cat >> "$I/Availability.h" <<'A'

/* tools/sdk/assemble-sdk.sh: the annotations are attributes only, left out in this tree */
#undef __API_AVAILABLE
#undef __API_DEPRECATED
#undef __API_DEPRECATED_WITH_REPLACEMENT
#undef __API_UNAVAILABLE
#undef __API_AVAILABLE_BEGIN
#undef __API_AVAILABLE_END
#undef __API_DEPRECATED_BEGIN
#undef __API_DEPRECATED_END
#undef __API_DEPRECATED_WITH_REPLACEMENT_BEGIN
#undef __API_DEPRECATED_WITH_REPLACEMENT_END
#undef __API_UNAVAILABLE_BEGIN
#undef __API_UNAVAILABLE_END
#define __API_AVAILABLE(...)
#define __API_DEPRECATED(...)
#define __API_DEPRECATED_WITH_REPLACEMENT(...)
#define __API_UNAVAILABLE(...)
#define __API_AVAILABLE_BEGIN(...)
#define __API_AVAILABLE_END
#define __API_DEPRECATED_BEGIN(...)
#define __API_DEPRECATED_END
#define __API_DEPRECATED_WITH_REPLACEMENT_BEGIN(...)
#define __API_DEPRECATED_WITH_REPLACEMENT_END
#define __API_UNAVAILABLE_BEGIN(...)
#define __API_UNAVAILABLE_END
#undef __SPI_AVAILABLE
#define __SPI_AVAILABLE(...)
#define __SPI_DEPRECATED(...)
#define __SPI_UNAVAILABLE(...)
A
# os/availability.h (the API_AVAILABLE family, generated by Apple): the same, empty
cat > "$I/os/availability.h" <<'A'
/* tools/sdk/assemble-sdk.sh: the API_* annotations are attributes only, left out in this tree */
#ifndef __OS_AVAILABILITY__
#define __OS_AVAILABILITY__
#include <Availability.h>
#define API_AVAILABLE(...)
#define API_DEPRECATED(...)
#define API_DEPRECATED_WITH_REPLACEMENT(...)
#define API_UNAVAILABLE(...)
#define API_AVAILABLE_BEGIN(...)
#define API_AVAILABLE_END
#define API_DEPRECATED_BEGIN(...)
#define API_DEPRECATED_END
#define API_DEPRECATED_WITH_REPLACEMENT_BEGIN(...)
#define API_DEPRECATED_WITH_REPLACEMENT_END
#define API_UNAVAILABLE_BEGIN(...)
#define API_UNAVAILABLE_END
#define SPI_AVAILABLE(...)
#define SPI_DEPRECATED(...)
#define SPI_DEPRECATED_WITH_REPLACEMENT(...)
#define API_NOT_DEPRECATED
#endif
A
# the test: a small C program against this tree and nothing else
RES=$(cc --print-resource-dir)/include
cat > "$W/sdk/t.c" <<T
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <unistd.h>
#include <pthread.h>
#include <dispatch/dispatch.h>
#include <mach/mach.h>
#include <mach-o/loader.h>
int main(void) { printf("%d\n", (int)sizeof(struct mach_header_64)); return 0; }
T
# the headers that are still missing are looked for in the fetched sources and copied in
sh "$H/resolve-headers.sh" "$W" "$W/sdk/t.c"
